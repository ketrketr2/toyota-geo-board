MODS = ["アクセサリー", "純正アクセサリー", "オプション", "カスタム", "パーツ"]
SEEDS = ["純正アクセサリー", "ディーラーオプション", "純正オプション", "カー用品", "カスタムパーツ", "おすすめ オプション"]


def model_keywords() -> list[str]:
    out = []
    for lst in MODELS.values():
        for _disp, names in lst:
            for n in names:
                out.append(n)
                out += [f"{n} {m}" for m in MODS]
    return out


def gads(kws: list[str]) -> dict:
    out = {}
    for i in range(0, len(kws), 900):
        chunk = kws[i:i + 900]
        try:
            task = llm._post("keywords_data/google_ads/search_volume/live",
                             [{"keywords": chunk, "language_code": LANG, "location_code": LOC}])
            got = task.get("result") or []
            for it in got:
                out[it["keyword"]] = {"v": it.get("search_volume"),
                                      "m": [[m.get("year"), m.get("month"), m.get("search_volume")]
                                            for m in (it.get("monthly_searches") or [])]}
            out[f"__status_{i}"] = {"code": task.get("status_code"), "msg": task.get("status_message"),
                                    "asked": len(chunk), "got": len(got)}
        except Exception as e:  # noqa: BLE001
            out[f"__error_{i}"] = str(e)[:300]
    return out


def labs(kws: list[str]) -> dict:
    out = {}
    for i in range(0, len(kws), 700):
        try:
            task = llm._post("dataforseo_labs/google/keyword_overview/live",
                             [{"keywords": kws[i:i + 700], "language_code": LANG, "location_code": LOC,
                               "include_clickstream_data": True}])
            for it in ((task.get("result") or [{}])[0].get("items") or []):
                ki = it.get("keyword_info") or {}
                out[it.get("keyword")] = {
                    "v": ki.get("search_volume"),
                    "vn": (it.get("keyword_info_normalized_with_clickstream") or {}).get("search_volume"),
                    "cs": (it.get("clickstream_keyword_info") or {}).get("search_volume"),
                    "upd": ki.get("last_updated_time")}
        except Exception as e:  # noqa: BLE001
            out[f"__error_{i}"] = str(e)[:300]
    return out


def suggest(seed: str) -> list:
    try:
        task = llm._post("dataforseo_labs/google/keyword_suggestions/live",
                         [{"keyword": seed, "language_code": LANG, "location_code": LOC, "limit": 300,
                           "include_seed_keyword": True, "order_by": ["keyword_info.search_volume,desc"]}])
        res = (task.get("result") or [{}])[0]
        return [{"kw": it.get("keyword"), "v": (it.get("keyword_info") or {}).get("search_volume")}
                for it in (res.get("items") or [])]
    except Exception as e:  # noqa: BLE001
        return [{"error": str(e)[:300]}]


def main():
    out = {"at_utc": datetime.datetime.utcnow().isoformat(), "mods": MODS,
           "cats": CATS, "models": {mk: [[d, ns] for d, ns in lst] for mk, lst in MODELS.items()}}
    cat_kws = [k for v in CATS.values() for k in v]
    all_kws = list(dict.fromkeys(cat_kws + model_keywords()))
    out["n_keywords"] = len(all_kws)
    out["gads"] = gads(all_kws)
    out["labs"] = labs(all_kws)
    out["suggest"] = {s: suggest(s) for s in SEEDS}
    out["spent"] = llm.spent()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "rank.json").write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")
    print(json.dumps({"n_keywords": out["n_keywords"], "gads": len(out["gads"]), "labs": len(out["labs"]),
                      "suggest": {k: len(v) for k, v in out["suggest"].items()}, "spent": out["spent"]},
                     ensure_ascii=False))


if __name__ == "__main__":
    main()
